import {launch,newPage} from './harness.mjs';
const {browser,BASE,server}=await launch();
let fail=0; const ok=(c,m)=>{ console.log((c?'PASS ':'FAIL ')+m); if(!c) fail++; };
const sleep=ms=>new Promise(r=>setTimeout(r,ms));
const P=await newPage(await browser.createBrowserContext(),BASE,{tables:{}});
await P.page.goto(`${BASE}/therapy/`,{waitUntil:'domcontentloaded'}); await sleep(800);
const t=await P.page.evaluate(()=>({text:document.body.innerText,links:[...document.querySelectorAll('main a')].map(a=>a.getAttribute('href'))}));
ok(/€80/.test(t.text)&&/€60/.test(t.text)&&/Introductory session/.test(t.text),'prices and the intro session are stated');
ok(/Nothing else, unless you share it/.test(t.text)&&/name, your email, whether you have a Lab plan/.test(t.text),'what the therapist sees matches the consent text');
ok(!/journal/i.test(t.text),'no claim that journal entries are shared');
ok(t.links.includes('/booking/')&&t.links.includes('/subscribe/'),'links to booking and Lab');
ok(P.errors.filter(e=>!/Failed to load resource/.test(e)).length===0,'no page errors '+P.errors.join('|'));
await P.page.goto(`${BASE}/dashboard/`,{waitUntil:'domcontentloaded'}); await sleep(1200);
const web=await P.page.evaluate(()=>({t:document.getElementById('bookCardTitle').textContent,h:document.getElementById('bookCard').getAttribute('href'),i:!document.getElementById('insightCard').hidden,b:!document.getElementById('checkinHero').hidden}));
ok(web.t==='Book a Session'&&web.h==='/booking/'&&!web.i&&!web.b,'the website dashboard keeps Book a Session and shows no app-only cards');
async function app(rows){ const A=await newPage(await browser.createBrowserContext(),BASE,{tables:{checkins:[],my_therapists:rows}});
  await A.page.evaluateOnNewDocument(()=>{ window.SIL_APP=true; });
  await A.page.goto(`${BASE}/dashboard/`,{waitUntil:'domcontentloaded'}); await sleep(1800);
  return A.page.evaluate(()=>({t:document.getElementById('bookCardTitle').textContent,h:document.getElementById('bookCard').getAttribute('href'),sep:!!document.getElementById('appTherapy')})); }
let a1=await app([]);
ok(/Therapy/.test(a1.t)&&a1.h==='/therapy/'&&!a1.sep,'app, no therapist yet: the bottom card is Therapy, and there is no extra card at the top');
a1=await app([{link_id:'L1',status:'active',user_id:'t1',display_name:'Dr R'}]);
ok(a1.t==='Book a Session'&&a1.h==='/booking/','app, therapist chosen: the card becomes Book a Session');
await browser.close(); server.close(); process.exit(fail?1:0);
