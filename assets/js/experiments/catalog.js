/**
 * /assets/js/experiments/catalog.js
 * The experiments, written as protocols. Plain data, so the same text can become a printed book.
 *
 * Every experiment is a small controlled experiment on your own music:
 *   question      what you are trying to find out
 *   hypothesis    a prediction that the result can support or fail to support
 *   variables     fixed (held still), changed (the one thing you vary), measured (what you write down)
 *   parameters    exact numbers: time, tempo, counts, tools allowed
 *   procedure     numbered steps, with the numbers in them
 *   trials        what you record, one row each
 *   stop          the rule that ends it
 *
 * tools: { type: 'gen', kind, ...spec }   a number / note / chord / rhythm generator
 *        { type: 'groove', steps, hits, bpm }  a repeating rhythm you play over
 *        { type: 'timer', minutes }
 *        { type: 'clip', ops: [...] }     load or record audio, then change it
 *        { type: 'loops', lengths: [..] } loops of different lengths running together
 *        { type: 'assign' }               give each of your things a new place
 */
